# 第 40 题：和为 K 的子数组（LeetCode 560）
# ============================================================
"""
题目描述
--------
给定一个整数数组 nums 和一个整数 k，请统计「和为 k 的连续子数组」的个数。
子数组必须是连续的（中间不能跳）。

输入：nums = [1,1,1], k = 2   输出：2   （[0..1] 和 [1..2] 两个子数组的和都是 2）
输入：nums = [1,2,3], k = 3   输出：2   （[0..1] 和 [2]）

通用解法（前缀和 + 哈希表）
-------------------------------------------
核心思想：子数组 nums[i..j] 的和 = 前缀和 pre[j+1] - pre[i]。
如果某个前缀和 s 之前「也出现过值等于 s - k 的前缀和」，那么中间这一段就是和为 k 的子数组。

做法：
1. 用一个哈希表 prefix 记录「到当前为止，各个前缀和出现了几次」。初始 prefix[0] = 1
   （前缀和为 0 出现 1 次，代表「还没开始」这个状态，用来处理从下标 0 开始的子数组）。
2. 从左到右遍历，累计当前前缀和 s（s 就是 nums[0..i] 的和）。
3. 查表：之前有多少个前缀和等于 s - k？这个数量就是「以当前 i 结尾、和为 k 的子数组个数」，
   累加到 count。
4. 把当前前缀和 s 计入哈希表（出现次数 +1）。

为什么对？因为 pre[j] - pre[i] = k  ⟺  pre[i] = pre[j] - k。我们每到一个新位置 j，
就去看前面有没有 pre[i] = pre[j] - k，有的话每一段 (i, j] 都是答案。

流程示意（nums = [1,1,1], k = 2）
--------------------------------------------------------------------------------
        s 初始 0，prefix = {0:1}，count = 0
i  x   s(累计和)   s-k    查 prefix[s-k]   累计 count   prefix（处理后）
-  -   --------   ----   ------------    ---------   -----------------------
       0                                               {0:1}
0  1     1        -1     无(0)           0            {0:1, 1:1}
1  1     2         0     有, prefix[0]=1 1            {0:1, 1:1, 2:1}
2  1     3         1     有, prefix[1]=1 2            {0:1, 1:1, 2:1, 3:1}

→ count = 2，对应子数组 [0..1]、[1..2]。
（注意前缀和相同代表「中间一段和为 0」，所以 s-k 出现几次就有几个新子数组）

复杂度
------
时间 O(n)，只遍历一次；空间 O(n)，哈希表最多存 n+1 个前缀和。

面试易错点
---------
1. 必须先把 prefix[0] = 1 放进去，否则「从下标 0 开始、和正好为 k」的子数组会被漏掉。
2. 顺序不能反：先 count += prefix[s-k]，再把 s 写进表。否则会把「当前这个 s」也算进去，
   而子数组至少要有一个元素，不能用自己减自己。
3. 这题和「最大子数组和」不同：最大和是 DP，这题是「计数」，必须用前缀和 + 哈希表。
"""


def subarray_sum(nums: list[int], k: int) -> int:
    count = 0
    prefix = {0: 1}          # 前缀和 0 出现 1 次（代表“还没取任何数”的状态）
    s = 0
    for x in nums:
        s += x
        count += prefix.get(s - k, 0)   # 前面有多少前缀和 == s-k，就有多少段和为 k
        prefix[s] = prefix.get(s, 0) + 1
    return count


