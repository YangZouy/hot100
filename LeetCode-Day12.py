# 第 43 题：除自身以外数组的乘积（LeetCode 238）
# ============================================================
"""
题目描述
--------
给定数组 nums，返回数组 answer，其中 answer[i] = 除 nums[i] 外其余元素的乘积。
要求：O(n) 时间，不能用除法，且除返回数组外空间复杂度 O(1)。

输入：nums = [1,2,3,4]   输出：[24,12,8,6]
  answer[0] = 2*3*4 = 24
  answer[1] = 1*3*4 = 12
  answer[2] = 1*2*4 = 8
  answer[3] = 1*2*3 = 6

通用解法（前缀积 + 后缀积，两次遍历）
---------------------------------------------------
answer[i] = （i 左边所有数的乘积）×（i 右边所有数的乘积）。
- 第一次从左往右：res[i] 先放「i 左边」的乘积，同时用 left 累乘。
- 第二次从右往左：用 right 累乘「i 右边」的乘积，res[i] *= right。
两个方向各扫一遍，谁也不乘自己，正好得到「除自身以外」的乘积。

流程示意（nums = [1,2,3,4]）
--------------------------------------------------------------------------------
nums:          [1,    2,    3,    4]
左→右(左积):   [1,    1,    2,    6]     res[i] = 左侧乘积，left 边走边乘
右→左(右积):   [24,   12,   8,    6]     right 从右累乘，res[i] *= right

具体：right 初始 1
  i=3: res[3]=6*1=6,  right=1*4=4
  i=2: res[2]=2*4=8,  right=4*3=12
  i=1: res[1]=1*12=12, right=12*2=24
  i=0: res[0]=1*24=24, right=24*1=24
→ [24,12,8,6]

复杂度
------
时间 O(n)，两趟遍历；空间 O(1)（输出数组 answer 不计入额外空间）。

面试易错点
---------
1. 题目禁止用除法：因为有 0 时除法会出错，而且可能溢出。前缀/后缀积才是正解。
2. 第一趟必须从 left=1 开始（不能用 0 当初始积），否则全变成 0。
3. 如果允许除法，更简单的做法是「总乘积 / nums[i]」，但要单独处理 0 的个数，反而易错，
   面试不推荐。
"""


def product_except_self(nums: list[int]) -> list[int]:
    n = len(nums)
    res = [1] * n
    left = 1
    for i in range(n):          # 第一趟：填好左侧乘积
        res[i] = left
        left *= nums[i]
    right = 1
    for i in range(n - 1, -1, -1):   # 第二趟：乘上右侧乘积
        res[i] *= right
        right *= nums[i]
    return res


