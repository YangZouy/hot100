# 第 44 题：找到数组中重复的数字（LeetCode 287）
# ============================================================
"""
题目描述
--------
给定长度为 n+1 的数组 nums，其中元素都在 [1, n] 范围内，且只有一个数字重复（可能重复多次）。
找出这个重复数字。进阶要求：空间 O(1)、时间 O(n)、不能修改原数组。

输入：nums = [1,3,4,2,2]   输出：2
输入：nums = [3,1,3,4,2]   输出：3

通用解法（Floyd 快慢指针 / 环检测）
-------------------------------------------------------
把数组看成「链表」：每个下标 i 指向 nums[i] 这个位置（i -> nums[i]）。
因为值都在 [1,n] 且有一个重复值，必然有两个下标指向同一个值 → 形成环。
重复的那个数字，正是「环的入口」。
这转化成了经典问题「链表找环入口」，用 Floyd 两步法：
  第一阶段（找相遇点）：slow 每次走 1 步，fast 每次走 2 步，二者必在环内相遇。
  第二阶段（找入口）：slow 回到起点，slow、fast 都每次走 1 步，再次相遇处即为环入口 = 重复数。

为什么对？第二阶段把 slow 拉回起点后，两者同速前进，相遇点恰好是环入口——这是
Floyd 算法证明过的结论（起点到入口距离 == 相遇点到入口距离）。

流程示意（nums = [1,3,4,2,2]，索引 0..4）
--------------------------------------------------------------------------------
把「下标 → 值」画成指针：
  0 → 1 → 3 → 2 → 4 → 2 → ...   （4 指向 2，于是 2→4→2 成环）
                         ↑_______│
                        重复数字 2 就是环的入口

slow/fast 轨迹：
  初始 slow=fast=0
  相遇阶段：slow:0→1→3→2→4   fast:0→3→4→4   （在 4 相遇）
  入口阶段：slow 回 0；slow:0→1→3→2   fast:4→2→...  在 2 相遇 → 返回 2

复杂度
------
时间 O(n)，slow/fast 最多走几倍 n；空间 O(1)，只用了两个指针。

面试易错点
---------
1. 这是面试高频题，考官往往就是要你写出 O(1) 空间的 Floyd。用哈希集合虽然 O(n) 空间
   更直觉，但拿不到加分。集合写法：seen=set(); for x in nums: if x in seen: return x; seen.add(x)。
2. 注意指针是「用值当下标」：slow = nums[slow]，fast = nums[nums[fast]]，别写成下标 +1。
3. 第二阶段一定要把 slow 重置回 0（起点），再和 fast（留在相遇点）同速走，否则找不到入口。
"""


def find_duplicate(nums: list[int]) -> int:
    slow = fast = 0
    # 第一阶段：找环内相遇点
    while True:
        slow = nums[slow]
        fast = nums[nums[fast]]
        if slow == fast:
            break
    # 第二阶段：slow 回起点，同速前进，相遇处即环入口（重复数）
    slow = 0
    while slow != fast:
        slow = nums[slow]
        fast = nums[fast]
    return slow


