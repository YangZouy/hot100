# 第 46–49 题：二叉树遍历（LeetCode 144 / 94 / 145 / 102）
# ============================================================
r"""
先放一个通用的树节点类和「用层序数组建树」的工具，方便跑测试。
后面四题都基于同一棵示例树：

        1
      /   \
     2     3
    / \   / \
   4   5 6   7

  - 前序(preorder)：根 → 左 → 右   → 1 2 4 5 3 6 7
  - 中序(inorder)：左 → 根 → 右   → 4 2 5 1 6 3 7
  - 后序(postorder)：左 → 右 → 根 → 4 5 2 6 7 3 1
  - 层序(level)：一层一层        → [[1],[2,3],[4,5,6,7]]
"""


class TreeNode:
    def __init__(self, val: int = 0, left: "TreeNode | None" = None,
                 right: "TreeNode | None" = None):
        self.val = val
        self.left = left
        self.right = right


def build_tree(vals) -> "TreeNode | None":
    """把 LeetCode 风格的层序数组（用 None 表示空节点）建成树。"""
    if not vals:
        return None
    root = TreeNode(vals[0])
    queue = [root]
    i = 1
    while queue and i < len(vals):
        node = queue.pop(0)
        if i < len(vals) and vals[i] is not None:
            node.left = TreeNode(vals[i])
            queue.append(node.left)
        i += 1
        if i < len(vals) and vals[i] is not None:
            node.right = TreeNode(vals[i])
            queue.append(node.right)
        i += 1
    return root


