# 第 47 题：二叉树的中序遍历（LeetCode 94）
# ============================================================
"""
题目描述
--------
返回二叉树的中序遍历（左 → 根 → 右）结果列表。

输入：[1,2,3,4,5,6,7]   输出：[4,2,5,1,6,3,7]

通用解法（用栈模拟递归，标准写法）
---------------------------------------------------
中序是「先一路向左到底，再访问节点，再转向右」，用栈模拟：
1. 当前节点 cur 不断往左走，沿途把经过的节点压栈（先不访问）。
2. 走不动了（cur 为空），弹出栈顶节点访问它（此时它的左子树已全部处理完）。
3. 把 cur 指向该节点的右孩子，继续重复「往左压栈」的过程。

流程示意（示例树）
--------------------------------------------------------------------------------
cur=1: 压1，cur=2；压2，cur=4；压4，cur=None
       栈(底→顶): |1|2|4|
弹出4 → 访问[4]，cur=4.right=None
弹出2 → 访问[4,2]，cur=2.right=5
cur=5: 压5，cur=None   栈:|1|5|
弹出5 → 访问[4,2,5]，cur=5.right=None
弹出1 → 访问[4,2,5,1]，cur=1.right=3
cur=3: 压3，cur=6；压6，cur=None   栈:|3|6|
弹出6 → 访问[...,6]，cur=6.right=None
弹出3 → 访问[...,6,3]，cur=3.right=7
cur=7: 压7，cur=None   栈:|7|
弹出7 → 访问[...,6,3,7]
结果：[4,2,5,1,6,3,7]  ✓

复杂度
------
时间 O(n)，空间 O(h)。

面试易错点
---------
1. 中序迭代比前序绕：容易忘了「先把整条左链压栈」这一步，直接访问根导致顺序错。
2. 二叉树「搜索树」的中序遍历是升序的，这是验证 BST 的经典性质，面试常连考。
3. 循环条件 `while cur or stack`，两个条件缺一不可，否则最后一段右子树会漏。
"""


def inorder_traversal(root: "TreeNode | None") -> list[int]:
    res = []
    stack = []
    cur = root
    while cur or stack:
        while cur:                  # 一路向左，沿途压栈
            stack.append(cur)
            cur = cur.left
        cur = stack.pop()           # 左到底了，访问栈顶
        res.append(cur.val)
        cur = cur.right             # 转向右子树
    return res


