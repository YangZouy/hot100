# 第 49 题：二叉树的层序遍历（LeetCode 102）
# ============================================================
"""
题目描述
--------
返回二叉树的层序遍历，结果按「层」分组（每一层一个子列表）。

输入：[1,2,3,4,5,6,7]   输出：[[1],[2,3],[4,5,6,7]]

通用解法（BFS + 队列）
---------------------------------------------------
用队列保存「当前层」的节点。每轮循环处理「当前队列里已有的全部节点」（即一整层）：
1. 队列初始放入根。
2. 每一轮先记下当前队列长度 size（这一层节点数），然后弹出 size 个节点，
   把它们的左右孩子加入队列。这一轮弹出的节点值就组成一层的列表。

为什么要先记 size：队列在循环中会不断加入下一层节点，必须用 size 锁住「本层边界」，
否则会把下一层的节点也算进当前层。

流程示意（示例树，队列用「左|右」表示）
--------------------------------------------------------------------------------
初始队列: [1]                         第1层: 弹出[1] → [1]
           加入 2,3 → 队列[2,3]
第2层: 弹出[2,3] → [2,3]             第2层结果
           加入 4,5,6,7 → 队列[4,5,6,7]
第3层: 弹出[4,5,6,7] → [4,5,6,7]     第3层结果
           无孩子，队列空，结束
结果：[[1],[2,3],[4,5,6,7]]  ✓

复杂度
------
时间 O(n)，空间 O(n)（队列最多存一层节点，最坏满二叉树最后一层约 n/2）。

面试易错点
---------
1. 「先记录 size 再循环 size 次」是层序分层的关键，漏了 size 就会把多层混在一起。
2. 加入孩子前要先判空（if node.left / if node.right），空节点不进队列。
3. 层序是很多树题（右视图、之字形、最大深度）的基础，务必一次写对。
"""


def level_order(root: "TreeNode | None") -> list[list[int]]:
    if not root:
        return []
    res = []
    q = deque([root])
    while q:
        level = []
        for _ in range(len(q)):        # 用 size 锁定本层边界
            node = q.popleft()
            level.append(node.val)
            if node.left:
                q.append(node.left)
            if node.right:
                q.append(node.right)
        res.append(level)
    return res


