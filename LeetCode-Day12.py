# 第 45 题：缺失数字（LeetCode 268）
# ============================================================
"""
题目描述
--------
给定范围 [0, n] 内的 n 个数（数组长度正好为 n），其中缺失了一个数，找出它。

输入：nums = [3,0,1]     输出：2   （0,1,2 里缺 2）
输入：nums = [0,1]       输出：2
输入：nums = [9,6,4,2,3,5,7,0,1]   输出：8

通用解法（位运算 XOR）
------------------------------------------------
性质：a ^ a = 0，a ^ 0 = a，且异或满足交换律。
把「下标 0..n-1」和「数组里的每个值」，再加上「长度 n」（相当于补一个下标 n），
全部异或在一起。出现两次的数会抵消为 0，最后剩下的就是只出现一次的那个——也就是缺失的数。

直观理解：完整集合 {0,1,2,...,n} 每个数出现两次（一次当下标、一次当值/长度），
缺失的数只在下标里出现一次（值里没有它），其余都成对抵消。

流程示意（nums = [3,0,1]，长度 n = 3）
--------------------------------------------------------------------------------
下标 i :   0    1    2         最后再 ^ n(=3)
值   v :   3    0    1
全部异或： 0^3 ^ 1^0 ^ 2^1 ^ 3
         = (0^0) (1^1) (3^3) 剩下 2  →  缺失的是 2

（也可用数学法：期望和 = n*(n+1)//2，减去数组实际和，差就是缺失数。两种方法都 O(n)/O(1)。）

复杂度
------
时间 O(n)，空间 O(1)。

面试易错点
---------
1. XOR 写法别漏了「最后再 ^ len(nums)」那一步——它补上了下标 n 本身，否则当缺失的是
   n 时会算错。
2. 数学法用求和时，n 很大要小心整数溢出（Python 无此问题，但 C++/Java 需注意用 long）。
3. 这题和「只出现一次的数字」(#136) 是亲兄弟，都是异或消对思想，可一并记忆。
"""


def missing_number(nums: list[int]) -> int:
    x = 0
    for i, v in enumerate(nums):
        x ^= i ^ v
    x ^= len(nums)        # 补上下标 n
    return x


