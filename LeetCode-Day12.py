# 第 48 题：二叉树的后序遍历（LeetCode 145）
# ============================================================
"""
题目描述
--------
返回二叉树的后序遍历（左 → 右 → 根）结果列表。

输入：[1,2,3,4,5,6,7]   输出：[4,5,2,6,7,3,1]

通用解法（前序变体 + 反转，最易记）
---------------------------------------------------
观察到：如果我们按「根 → 右 → 左」的顺序遍历，得到的结果正好是「后序」的【逆序】。
所以：
1. 复用前序的栈写法，但改成「先压左、后压右」——出栈顺序就变成 根→右→左。
2. 把收集到的列表整体反转，得到 左→右→根，即后序。

流程示意（示例树）
--------------------------------------------------------------------------------
按 根→右→左 收集：1,3,7,6,2,5,4
反转后：            4,5,2,6,7,3,1  = 后序  ✓

（另一套「真实模拟」写法是用一个 prev 指针判断右子树是否访问过，但记忆成本高，
 面试首选「前序变体 + 反转」这个简洁版本。）

复杂度
------
时间 O(n)，空间 O(h)。

面试易错点
---------
1. 反转版本里压栈顺序要和前序相反：先左后右，这样出栈才是 根→右→左。
2. 最后一步 `res[::-1]` 别忘，否则出来的是 根→右→左。
3. 后序是三种遍历里最容易手撕出错的，强烈建议面试前把这套「反转法」默写一遍。
"""


def postorder_traversal(root: "TreeNode | None") -> list[int]:
    if not root:
        return []
    res = []
    stack = [root]
    while stack:
        node = stack.pop()
        res.append(node.val)
        if node.left:              # 先压左、后压右 → 出栈顺序 根→右→左
            stack.append(node.left)
        if node.right:
            stack.append(node.right)
    return res[::-1]               # 反转得到 后序 左→右→根


