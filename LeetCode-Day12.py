# 第 46 题：二叉树的前序遍历（LeetCode 144）
# ============================================================
"""
题目描述
--------
返回二叉树的前序遍历（根 → 左 → 右）结果列表。

输入：[1,2,3,4,5,6,7]（层序）  输出：[1,2,4,5,3,6,7]

通用解法（用栈模拟递归，最简单写法）
---------------------------------------------------
思路：根节点先访问，再左、再右。用栈后进先出反着来：
1. 把根压栈。
2. 循环：弹出节点 → 访问它（加入结果）→ 先压右孩子，再压左孩子
   （因为栈是 LIFO，想让左孩子先被处理，就得后压左，所以右先压、左后压）。
这样出栈顺序就是 根→左→右，完美对应前序。

流程示意（示例树，栈用「底|...|顶」表示）
--------------------------------------------------------------------------------
压入 1：           栈: |1|
弹出 1 → 访问[1]   压右3、压左2：  栈: |3|2|
弹出 2 → 访问[1,2] 压右5、压左4：  栈: |3|5|4|
弹出 4 → 访问[1,2,4] 无孩子：       栈: |3|5|
弹出 5 → 访问[1,2,4,5] 无孩子：     栈: |3|
弹出 3 → 访问[1,2,4,5,3] 压右7、压左6：栈: |7|6|
弹出 6 → 访问[...,6]                栈: |7|
弹出 7 → 访问[...,7]                栈: 空
结果：[1,2,4,5,3,6,7]  ✓

复杂度
------
时间 O(n)（每个节点进出栈各一次），空间 O(h)（h 为树高，最坏 O(n) 退化为链）。

面试易错点
---------
1. 压栈顺序一定是「先右后左」，写反了就变成 根→右→左 了。
2. 空树要返回 []，别返回 [None]。
3. 前序的迭代写法比递归略长，但面试常要求「不用递归」，这套栈写法必须会。
"""


def preorder_traversal(root: "TreeNode | None") -> list[int]:
    if not root:
        return []
    res = []
    stack = [root]
    while stack:
        node = stack.pop()
        res.append(node.val)
        if node.right:
            stack.append(node.right)
        if node.left:
            stack.append(node.left)
    return res


