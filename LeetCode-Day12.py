# 第 41 题：连续子数组的最大和（LeetCode 53）
# ============================================================
"""
题目描述
--------
给定一个整数数组 nums，找出一个具有最大和的连续子数组，返回其最大和。

输入：nums = [-2,1,-3,4,-1,2,1,-5,4]   输出：6   （子数组 [4,-1,2,1]）
输入：nums = [1]                       输出：1
输入：nums = [-1,-2,-3]                输出：-1  （全负数时返回最大的那个负数）

通用解法（Kadane 算法 / 动态规划）
-----------------------------------------------------------
定义 cur 表示「以当前元素 x 结尾的最大子数组和」。
对于 x，你有两个选择：
  a) 把 x 接到前面那段后面：cur + x
  b) 不如自己单开一段只含 x：x
所以 cur = max(x, cur + x)。
best 记录全局最大值，每步 best = max(best, cur)。
一句话：当前段一旦变负，就果断丢弃、从 x 重新开始（负收益只会拖累后面）。

流程示意（nums = [-2,1,-3,4,-1,2,1,-5,4]）
--------------------------------------------------------------------------------
x      cur = max(x, cur+x)        best = max(best, cur)
-      --------------------       --------------------
-2     -2                         -2
 1     max(1, -2+1=-1) = 1         1
-3     max(-3, 1-3=-2) = -2       -2
 4     max(4, -2+4=2) = 4          4
-1     max(-1, 4-1=3) = 3          4
 2     max(2, 3+2=5) = 5           5
 1     max(1, 5+1=6) = 6           6
-5     max(-5, 6-5=1) = 1          6
 4     max(4, 1+4=5) = 5           6

→ best = 6，对应子数组 [4,-1,2,1]。

复杂度
------
时间 O(n)，空间 O(1)（只用了两个变量）。

面试易错点
---------
1. 初始化不能写 best = 0！数组可能全是负数，0 比任何负数都大，会错。
   正确做法：best = cur = nums[0]，从第一个元素起算。
2. 这题只求「和」，若面试要求「返回这个子数组本身」，再多记一下 start/end 下标即可，
   核心逻辑不变。
3. 别和前缀和搞混：这里要的是最大值，不是子数组个数，Kadane 比前缀和更直接。
"""


def max_sub_array(nums: list[int]) -> int:
    best = cur = nums[0]
    for x in nums[1:]:
        cur = max(x, cur + x)   # 要么接在前面，要么自己单开
        best = max(best, cur)
    return best


