# 第 42 题：乘积最大子数组（LeetCode 152）
# ============================================================
"""
题目描述
--------
给定整数数组 nums，找出乘积最大的连续子数组，返回其最大乘积。

输入：nums = [2,3,-2,4]     输出：6    （[2,3] 乘积 6；注意不能取全部，2*3*-2*4 = -48）
输入：nums = [-2,0,-1]      输出：0    （取 [0]）
输入：nums = [-2,3,-4]      输出：24   （[-2,3,-4] 乘积 24）

通用解法（动态规划，同时维护「以当前结尾的最大积」和「最小积」）
--------------------------------------------------------------------
难点：负数 × 负数 = 正数。一个很小的负数，遇到下一个负数可能变成最大的。
所以每个位置我们同时记录：
  cur_max = 以 x 结尾的最大乘积
  cur_min = 以 x 结尾的最小乘积
对 x 而言，候选值只有三个：x 自己、cur_max*x、cur_min*x（因为上一个 min 可能是个大负数）。
  cur_max = max(x, cur_max*x, cur_min*x)
  cur_min = min(x, cur_max_old*x, cur_min_old*x)
⚠️ 关键：先比较再更新，且更新 cur_max 时要用「上一轮的 cur_min」，所以遇到
负数时先把两者交换再统一算，能避免用到刚被改过的 cur_max。

流程示意（nums = [2,3,-2,4]）
--------------------------------------------------------------------------------
x    交换?   cur_max = max(x, cm*x)   cur_min = min(x, cmin*x)   best
-    ----    ----------------------   -----------------------   ----
2     -      max(2, 2*2=4?)→初值2     min(2, 2*2?)→初值2         2
3     -      max(3, 2*3=6)=6          min(3, 2*3=6)=3            6
-2   是(交换) max(-2, 2*-2=-6)=-2     min(-2, 6*-2=-12)=-12      6
4     -      max(4, -2*4=-8)=4        min(4, -12*4=-48)=-48      6

→ best = 6，对应子数组 [2,3]。

复杂度
------
时间 O(n)，空间 O(1)。

面试易错点
---------
1. 不能直接套「最大子数组和」改成乘积：因为负负得正，最大和那套 max(x, cur+x) 会错。
2. 一定要同时维护 cur_min。漏掉它，遇到 [-2,3,-4] 这种会算错（正确答案是 24 不是 3）。
3. 更新顺序：交换/比较必须基于「上一轮」的 cur_max、cur_min，别在算 cur_max 时用了
   已经被本轮回写过的 cur_min。
"""


def max_product(nums: list[int]) -> int:
    best = cur_max = cur_min = nums[0]
    for x in nums[1:]:
        if x < 0:                      # 乘负数会让大小反转，先交换
            cur_max, cur_min = cur_min, cur_max
        cur_max = max(x, cur_max * x)
        cur_min = min(x, cur_min * x)
        best = max(best, cur_max)
    return best


