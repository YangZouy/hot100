# 第 3 题：移动零（LeetCode 283）
# ============================================================
"""
题目描述
--------
给定一个数组 nums，编写一个函数将所有 0 移动到数组末尾，
同时保持非零元素的相对顺序。必须在原数组上「原地」操作，不能复制数组。

示例：
    输入：nums = [0, 1, 0, 3, 12]
    输出：[1, 3, 12, 0, 0]

思路：快慢双指针（一次遍历 + 交换）
----------------------------------
想象两个指针：
  - slow：指向「下一个非零元素应该放的位置」
  - fast：从头扫到尾，专门找非零元素
当 fast 遇到非零元素时，把它和 slow 位置的元素交换，然后 slow 前进一步。
这样非零元素被依次「交换」到前面，0 被逐渐挤到后面。一趟就搞定。

为什么非零元素顺序不会乱？
  fast 是从左到右扫的，先遇到的非零元素先被换到前面，相对顺序天然保留。
为什么能原地？全程只做元素交换，没用额外数组。

流程示意（nums = [0, 1, 0, 3, 12]）
------------------------------------
slow=0 fast=0 : nums[0]=0 -> 不动, slow=0
slow=0 fast=1 : nums[1]=1 -> 交换(0,1) -> [1,0,0,3,12], slow=1
slow=1 fast=2 : nums[2]=0 -> 不动
slow=1 fast=3 : nums[3]=3 -> 交换(1,3) -> [1,3,0,0,12], slow=2
slow=2 fast=4 : nums[4]=12-> 交换(2,4) -> [1,3,12,0,0], slow=3
结束 -> [1, 3, 12, 0, 0] ✅

复杂度：
  时间 O(n)   空间 O(1)
面试易错点：
  - 题目要求原地操作，别新建数组。
  - 交换写法一次遍历即可，比「先搬非零再补零」更简洁，面试推荐写交换版。
"""

