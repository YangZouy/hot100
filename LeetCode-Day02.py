"""
题目描述
--------
给定一个整数数组 nums，将数组中的元素向右轮转 k 个位置，k 为非负数。

示例：
    输入：nums = [1, 2, 3, 4, 5, 6, 7], k = 3
    输出：[5, 6, 7, 1, 2, 3, 4]
    解释：右移 3 步后，最后 3 个元素 [5,6,7] 跑到了最前面。

思路：三次翻转（最优解，O(n) 时间，O(1) 空间）
-------------------------------------------
这道题有三种常见思路，但面试最爱的「巧妙且最优」解法是三次翻转：
  1) 额外数组：new[(i+k)%n] = nums[i]  -> O(n) 空间，不是最优
  2) 暴力：每次把最后元素挪到最前，重复 k 次 -> O(k*n)，太慢
  3) 三次翻转：先整体翻，再分别翻两段 -> O(n) 时间，O(1) 空间 ✅

原理：翻转两次等于复原。把数组看成两段——
    后 k 个（要移到前面）和 前 n-k 个（要移到后面）。
  - 步骤1 整体翻转：让两段「调了个头」
  - 步骤2 翻转前 k 个：把后面那段翻回正常顺序
  - 步骤3 翻转剩余 n-k 个：把前面那段也翻回正常顺序
记得先 k = k % n：轮转 n 次等于没转，k>n 时做无用功甚至出错。

流程示意（nums = [1, 2, 3, 4, 5, 6, 7], k = 3）
-------------------------------------------------
整体翻转 : [7, 6, 5, 4, 3, 2, 1]
翻前 3 个: [5, 6, 7, 4, 3, 2, 1]
翻后 4 个: [5, 6, 7, 1, 2, 3, 4] ✅

复杂度：
  时间 O(n)（每个元素最多被交换两次）  空间 O(1)
面试易错点：
  - 忘写 k = k % n 会在 k>n 时出错。
  - 翻转顺序是「整体 -> 前k -> 剩余」，别写反。
  - 面试官问「有没有 O(1) 空间做法」时，这就是标准答案，要练到闭眼能写。
"""

