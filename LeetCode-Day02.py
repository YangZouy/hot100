# 第四题 旋转数组：三次翻转
def rotate(nums: list[int], k: int) -> None:
    def reverse(left: int, right: int):
        while (left < right):
            nums[left], nums[right] = nums[right], nums[left]
            left += 1
            right -= 1

    n = len(nums)
    k = k % n
    if k == 0:
      return
    reverse(0, n-1)
    reverse(0, k-1)
    reverse(k, n-1)

