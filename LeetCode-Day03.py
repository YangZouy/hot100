def is_valid(s: str) -> bool:
    pair = {"}": "{", ")": "(", "]": "["}
    stack:list[str] = []

    for char in s:
        if char in pair:
            if not stack or stack.pop() != pair[char]:
                return False
        else:
            stack.append(char)
    return len(stack) == 0

