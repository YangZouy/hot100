"""
题目描述
--------
给你一个长度为 n 的整数数组 nums，其中 nums[i] 都在区间 [1, n] 内。
有些数字出现了两次，有些数字一次也没出现。
请找出所有在 [1, n] 范围内、但没有出现在 nums 中的数字。

要求（面试常加）：时间复杂度 O(n)，且只用常数额外空间——可以修改原数组。

示例：
    输入：nums = [4, 3, 2, 7, 8, 2, 3, 1]
    输出：[5, 6]        # 1~8 中，5 和 6 没出现

思路：原地标记法（用正负号当布尔数组）
-----------------------------------
核心想法：数组下标 0..n-1 天然可以当作「数字 1..n」的标记位。
我们规定——如果数字 x 出现过，就把下标 x-1 位置上的数「标记为负」。
遍历结束后，下标 i 位置上的数如果还是正数，说明数字 i+1 没出现过。

为什么可行 / 为什么不会漏标？
  - 每个数都在 [1, n]，所以 x-1 一定是合法下标，不会越界。
  - 用 abs(num) 取「原本的数字」再减 1：因为该位置可能已经被前面的数标成负的，
    取绝对值才能拿到真正想标记的那个下标。
  - 只在「当前位置还是正数」时才取反，避免重复取反导致又变回正数。

流程示意（nums = [4, 3, 2, 7, 8, 2, 3, 1]）
------------------------------------------------
初始  : [ 4,  3,  2,  7,  8,  2,  3,  1]
读 4  -> 标记 idx=3 -> [ 4,  3,  2, -7,  8,  2,  3,  1]
读 3  -> 标记 idx=2 -> [ 4,  3, -2, -7,  8,  2,  3,  1]
读 2  -> 标记 idx=1 -> [ 4, -3, -2, -7,  8,  2,  3,  1]
读 7  -> 标记 idx=6 -> [ 4, -3, -2, -7,  8,  2, -3,  1]
读 8  -> 标记 idx=7 -> [ 4, -3, -2, -7,  8,  2, -3, -1]
读 2  -> 标记 idx=1 -> 已负，跳过
读 3  -> 标记 idx=2 -> 已负，跳过
读 1  -> 标记 idx=0 -> [-4, -3, -2, -7,  8,  2, -3, -1]
最终  : [-4, -3, -2, -7,  8,  2, -3, -1]
下标  :   0    1    2    3    4   5    6    7
正数出现在下标 4、5 -> 对应数字 5、6 没出现 ✅

复杂度：
  时间 O(n)（两遍扫描）   空间 O(1)（不计返回的答案列表）
面试易错点：
  - 一定要用 abs(num) 取原值，否则已经被标负的元素会得出错误下标。
  - 别用「额外数组计数」的解法（空间 O(n)），本题面试常要求 O(1) 空间。
  - 变体：找「重复的数字」「缺失的一个数字」都是同一类「原地利用数组当下标」的思路。
"""

