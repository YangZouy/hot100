def find_disappeared_numbers(nums: list[int]) -> list[int]:
    n = len(nums)
    for num in nums:
        index = abs(num) - 1
        if nums[index] > 0:
            nums[index] = -nums[index]

    result = []
    for i, num in enumerate(nums, 1):
        if num > 0:
            result.append(i)
    return result

