"""
题目描述
--------
给定一个只包含 '('、')'、'{'、'}'、'['、']' 的字符串 s，
判断字符串是否有效。有效需满足：
  1) 左括号必须用相同类型的右括号闭合；
  2) 左括号必须以正确的顺序闭合。

示例：
    输入：s = "()[]{}"   输出：True
    输入：s = "(]"       输出：False
    输入：s = "([)]"     输出：False

思路：栈（Stack）
----------------
括号匹配是「后进先出」的典型场景，最适合用栈。规则：
  - 遇到左括号：入栈。
  - 遇到右括号：栈顶必须是对应的左括号——匹配则出栈；不匹配（或栈已空）则无效。
  - 遍历结束后，栈必须为空（所有左括号都被闭合了）。

为什么用栈？
  「最后打开的括号必须最先闭合」，这正是栈的 LIFO（后进先出）特性。

流程示意（s = "{[()]}"，有效）
----------------------------------
读 {  -> 栈: ['{']
读 [  -> 栈: ['{', '[']
读 (  -> 栈: ['{', '[', '(']
读 )  -> 栈顶 '(' 匹配 -> 出栈 -> 栈: ['{', '[']
读 ]  -> 栈顶 '[' 匹配 -> 出栈 -> 栈: ['{']
读 }  -> 栈顶 '{' 匹配 -> 出栈 -> 栈: []
结束：栈空 -> 有效 ✅

流程示意（s = "([)]"，无效）
----------------------------------
读 (  -> 栈: ['(']
读 [  -> 栈: ['(', '[']
读 )  -> 栈顶是 '['，但 ')' 需要 '(' -> 不匹配 -> 立即返回 False ❌

复杂度：
  时间 O(n)（扫一遍）   空间 O(n)（栈最坏存 n/2 个左括号）
面试易错点：
  - 用哈希表 pair = {')':'(', '}':'{', ']':'['} 把「右->左」对应关系写清楚，代码最简洁。
  - 别忘了最后判断「栈是否为空」：像 "((((" 这种，遍历完栈非空，也是无效。
  - 遇到右括号时栈已空，说明没有可匹配的左括号，直接 False。
"""

