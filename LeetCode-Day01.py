# ============================================================
# 第 1 题：两数之和（LeetCode 1）
# ============================================================
"""
题目描述
--------
给定一个整数数组 nums 和一个整数目标值 target，
请在数组中找出「和为 target」的两个整数，并返回它们的下标。
（题目保证恰好有一组解，且同一个元素不能重复使用。）

示例：
    输入：nums = [2, 7, 11, 15], target = 9
    输出：[0, 1]        # 因为 nums[0] + nums[1] == 2 + 7 == 9

思路：哈希表「边走边查」（一遍遍历）
-----------------------------------
最直观是双重循环 O(n^2)。优化思路：用哈希表记住「已经看过的数 -> 它的下标」。
对当前数 num，我们算「补数」complement = target - num，然后看补数在不在哈希表里：
  - 在  -> 直接返回 [补数的下标, 当前下标]
  - 不在 -> 把 (num, 当前下标) 存进哈希表，继续往后走
这样每个数只访问一次，时间复杂度 O(n)。

为什么是「边走边查」而不是「先把整张表建好再查」？
  - 如果先把所有数都存进哈希表再查，遇到 [3, 3] target=6 这种
    「同一个值出现在两个不同位置」的情况会出错（表里只有一对 3，区分不了两个下标）。
  - 边走边查保证：查的时候哈希表里只有「当前元素之前的数」，
    天然排除自己，绝不会用同一个元素两次。

流程示意（nums = [2, 7, 11, 15], target = 9）
------------------------------------------------
i=0 num=2 : 查补数 7 在表? 否 -> 表 = {2:0}
i=1 num=7 : 查补数 2 在表? 是 -> 返回 [表[2]=0, i=1] = [0, 1] ✅

复杂度：
  时间 O(n)（一遍遍历）   空间 O(n)（哈希表最多存 n 个元素）
"""

def two_sum(nums: list[int], target: int) -> list[int]:
    """
    哈希表边走边查。返回两个下标；题目保证有解，正常不会走到最后。
    """
    # seen: dict[int, int] = {}          # 值 -> 下标
    # for i, num in enumerate(nums):
    #     complement = target - num
    #     if complement in seen:
    #         return [seen[complement], i]
    #     seen[num] = i
    # return []                          # 理论不可达

    seen = {}
    for i, num in enumerate(nums):
        obj = target - num
        # 遍历的是字典的键
        # seen.values()是值
        # seen.items()是键值对
        if obj in seen:
            return [seen[obj], i]
        seen[num] = i
    return []
      


