# 第 2 题：合并两个有序数组（LeetCode 88）
# ============================================================
"""
题目描述
--------
给你两个按「非递减顺序」排列的整数数组 nums1 和 nums2。
nums1 有 m 个有效元素，其后预留了 n 个 0 当空位（长度 = m + n）。
请把 nums2 合并到 nums1 中，使 nums1 成为一个整体有序的数组（原地，不返回新数组）。

示例：
    nums1 = [1, 2, 3, 0, 0, 0], m = 3
    nums2 = [2, 5, 6],            n = 3
    合并后 nums1 = [1, 2, 2, 3, 5, 6]

思路：从后往前填（双指针）
-------------------------
如果从左往右填，nums1 前面的数会被覆盖、丢失。
所以反过来：用三个指针
    i -> nums1 有效部分的末尾（从 m-1 开始）
    j -> nums2 的末尾（从 n-1 开始）
    k -> nums1 物理位置的末尾（从 m+n-1 开始）
每次把「i 和 j 中较大的那个」放到 k 位置，然后对应指针和 k 都前移一格。
最后如果 nums2 还有剩（j >= 0，说明 nums1 已用完），直接把剩余补到前面；
nums1 自己剩的不用动（本来就在那）。

流程示意（nums1=[1,2,3,0,0,0], nums2=[2,5,6]）
------------------------------------------------
i=2 j=2 k=5 : 比 3 vs 6 -> 放 6 -> [1,2,3,0,0,6]
i=2 j=1 k=4 : 比 3 vs 5 -> 放 5 -> [1,2,3,0,5,6]
i=2 j=0 k=3 : 比 3 vs 2 -> 放 3 -> [1,2,3,3,5,6]
i=1 j=0 k=2 : 比 2 vs 2 -> 放 2 -> [1,2,2,3,5,6]
i=1 j=-1 结束 -> 结果 [1,2,2,3,5,6] ✅

复杂度：
  时间 O(m + n)   空间 O(1)（原地修改）
"""

def merge(nums1: list[int], m: int, nums2: list[int], n: int) -> None:
    """
    从后往前合并，避免覆盖 nums1 中尚未处理的有效元素。
    """
    # i, j, k = m - 1, n - 1, m + n - 1
    # while i >= 0 and j >= 0:
    #     if nums1[i] > nums2[j]:
    #         nums1[k] = nums1[i]
    #         i -= 1
    #     else:
    #         nums1[k] = nums2[j]
    #         j -= 1
    #     k -= 1
    # # nums2 还有剩余（nums1 已用完），直接补到前面
    # while j >= 0:
    #     nums1[k] = nums2[j]
    #     j -= 1
    #     k -= 1

    k = m + n -1
    i = m - 1
    j = n - 1
    while i >= 0 and j >= 0:
        if nums1[i] > nums2[j]:
            nums1[k] = nums1[i]
            i -= 1
        else:
            nums1[k] = nums2[j]
            j -= 1
        k -= 1
    while j >= 0:
        nums1[k] = nums2[j]
        j -= 1
        k -= 1
    


